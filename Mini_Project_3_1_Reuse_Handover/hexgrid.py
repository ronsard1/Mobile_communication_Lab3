"""
hexgrid.py - hexagonal cell layout and frequency-reuse labelling (Mini Project 3.1 part (a)).

Axial coordinates (q, r), pointy-top hexagons of radius R (centre to corner):
    x = R * sqrt(3) * (q + r/2),   y = R * 1.5 * r
Neighbouring centres are sqrt(3)*R apart.

Cluster tiling: for N = i^2 + i*j + j^2 the co-channel cells form the lattice generated by
    a = (i, j)          and          b = (-j, i + j)        (b is a rotated by 60 degrees)
whose fundamental cell contains exactly det[a b] = N hexagons. The frequency group of a hexagon
is its residue modulo that lattice, so two hexagons share a group exactly when their offset is an
integer combination of a and b. The co-channel distance is |a| = sqrt(3N) * R.
"""
from __future__ import annotations

import math

import numpy as np

# the (i, j) shift pair for each valid cluster size
SHIFT = {1: (1, 0), 3: (1, 1), 4: (2, 0), 7: (2, 1), 9: (3, 0), 12: (2, 2), 13: (3, 1), 19: (3, 2), 21: (4, 1)}


def valid_cluster_sizes(limit=30):
    return sorted({i * i + i * j + j * j for i in range(0, 7) for j in range(0, 7)
                   if 0 < i * i + i * j + j * j <= limit})


def hex_cells(rings: int):
    """Axial coordinates of all hexagons within `rings` rings of the origin (1 + 3k(k+1) cells)."""
    out = []
    for q in range(-rings, rings + 1):
        for r in range(max(-rings, -q - rings), min(rings, -q + rings) + 1):
            out.append((q, r))
    return out


def center(q, r, R=1.0):
    return R * math.sqrt(3) * (q + r / 2.0), R * 1.5 * r


def group_labeller(N: int):
    """Return a function (q, r) -> group 1..N for cluster size N."""
    i, j = SHIFT[N]
    reps = {}

    def residue(q, r):
        # coordinates of (q, r) in the lattice basis a=(i,j), b=(-j,i+j); inverse matrix = adj / N
        m = math.floor(((i + j) * q + j * r) / N)
        n = math.floor((-j * q + i * r) / N)
        return (q - m * i + n * j, r - m * j - n * (i + j))

    # enumerate the N residues in a fixed order so labels are stable (1 = the origin's group)
    order = []
    for rad in range(0, 8):
        for (q, r) in sorted(hex_cells(rad), key=lambda c: (max(abs(c[0]), abs(c[1]), abs(c[0] + c[1])), c)):
            res = residue(q, r)
            if res not in reps:
                reps[res] = len(reps) + 1
                order.append(res)
        if len(reps) == N:
            break
    assert len(reps) == N, f"cluster size {N}: found {len(reps)} groups"
    return lambda q, r: reps[residue(q, r)]


def layout(N: int, rings: int, R=1.0):
    lab = group_labeller(N)
    cells = hex_cells(rings)
    return [(q, r, *center(q, r, R), lab(q, r)) for (q, r) in cells]


def measured_reuse_distance(cells, R=1.0):
    """Smallest centre-to-centre distance between two different cells of the same group."""
    pts = np.array([[c[2], c[3]] for c in cells])
    g = np.array([c[4] for c in cells])
    best = np.inf
    for k in np.unique(g):
        p = pts[g == k]
        if len(p) < 2:
            continue
        d = np.sqrt(((p[:, None, :] - p[None, :, :]) ** 2).sum(-1))
        d[d == 0] = np.inf
        best = min(best, d.min())
    return best / R
